"""SMT-LIB v2 export of contract checks.

Interoperability with other SMT solvers (roadmap section 2.4). The scripts are
generated by Z3's own serializer (Solver.to_smt2) from the same expressions
ContractVerifier checks, so they cannot drift from what verify_contract decides.

This replaces the v7.0 SMTLibExporter, which declared fixed `x`/`result`
variables and pasted contract strings as-is. Coq and Lean 4 export are not
restored: they had no working translation.
"""
from typing import Any, Dict, List, Optional

from .contract_verifier import (
    Z3_AVAILABLE,
    ContractSpec,
    ContractVerifier,
    _RESULT_ALIASES,
    _clause_to_z3,
    _is_z3_bool,
)
from . import z3_builtins

if Z3_AVAILABLE:
    import z3


def export_smtlib(code: str, contract: Optional[ContractSpec] = None) -> List[Dict[str, Any]]:
    """Return one SMT-LIB script per checkable postcondition.

    Each entry has:
        clause:   the postcondition text
        check:    "implication" or "satisfiability"
        expected: "unsat" if the solver should confirm the clause, "sat" otherwise

    Implication checks assert the preconditions and the negated postcondition,
    so unsat means the preconditions imply the postcondition. Postconditions
    that mention the return value get a satisfiability check only, matching
    verify_contract. Postconditions that cannot be translated are left out.
    Returns an empty list when Z3 is not installed.
    """
    if not Z3_AVAILABLE:
        return []
    if contract is None:
        contract = ContractVerifier.parse_contract(code)

    env: Dict[str, Any] = {}
    z3_builtins.seed_string_env(
        contract.preconditions + contract.postconditions + contract.invariants, env,
    )
    preconditions = [
        expr for expr in (_clause_to_z3(c, env) for c in contract.preconditions)
        if expr is not None and _is_z3_bool(expr)
    ]

    scripts: List[Dict[str, Any]] = []
    for clause in contract.postconditions:
        expr = _clause_to_z3(clause, env)
        if expr is None or not _is_z3_bool(expr):
            continue
        solver = z3.Solver()
        if any(alias in clause.lower() for alias in _RESULT_ALIASES):
            solver.add(expr)
            check, expected = "satisfiability", "sat"
        else:
            for pre in preconditions:
                solver.add(pre)
            solver.add(z3.Not(expr))
            check, expected = "implication", "unsat"
        scripts.append({
            "clause": clause,
            "check": check,
            "expected": expected,
            "smt2": solver.to_smt2(),
        })
    return scripts
